// Build-only Z2 inverse fit. Never changes the legacy registry or RK4 equations.
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {CATALOG} from '../apps/training/src/catalog.js';
import {getVelocityDragClass} from '../apps/training/src/generated/legacy-flight.js';
import {solveZero,flightAtDistance} from './training-zeroing-solver.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function generateFlightTuning(){
 const old=JSON.parse(await readFile(resolve(root,'docs/zeroing-ledger-v30.json'),'utf8'));
 const preset=old.presets.find(p=>p.opticId==='trijicon_ta31'),ranges=[400,500,600],marks=[7.8,12.6,18.7];
 const evaluate=R=>{
  const options={retentionByCaliber:{'5.56x45mm':R}},p=solveZero(preset,options);
  const rows=ranges.map((distanceM,i)=>{
   const f=flightAtDistance(p,p.thetaRad,distanceM,p.referenceAmmoId,options),dropMOA=-Math.atan2(f.heightM,distanceM)*10800/Math.PI;
   return {distanceM,markMOA:marks[i],gameDropMOA:dropMOA,errorMOA:dropMOA-marks[i]};
  });return {R,thetaRad:p.thetaRad,rows,squaredErrorMOA:rows.reduce((sum,r)=>sum+r.errorMOA**2,0)};
 };
 // Golden-section search on a bracket much wider than the suggested R=.886.
 let lo=.75,hi=.98;const ratio=(Math.sqrt(5)-1)/2;
 let x1=hi-ratio*(hi-lo),x2=lo+ratio*(hi-lo),a=evaluate(x1),b=evaluate(x2);
 for(let i=0;i<42;i++){
  if(a.squaredErrorMOA>b.squaredErrorMOA){lo=x1;x1=x2;a=b;x2=lo+ratio*(hi-lo);b=evaluate(x2);}
  else {hi=x2;x2=x1;b=a;x1=hi-ratio*(hi-lo);a=evaluate(x1);}
 }
 const fitted=evaluate((lo+hi)/2),overrides={'5.56x45mm':fitted.R};
 const mapping=Object.entries(CATALOG.AMMO_PRESETS).filter(([,a])=>/^5\.56[×x]45(?:mm)?$/i.test(a.caliber||'')).map(([ammoId,ammo])=>{
  const legacyDragClass=getVelocityDragClass(ammo),legacyRetentionPer100M=CATALOG.DRAG_RETENTION_PER_100M[legacyDragClass]||.93;
  return {ammoId,caliber:ammo.caliber,legacyDragClass,legacyRetentionPer100M,
   classRatioToRifleLight:legacyRetentionPer100M/CATALOG.DRAG_RETENTION_PER_100M.rifle_light,
   retentionPer100M:fitted.R*legacyRetentionPer100M/CATALOG.DRAG_RETENTION_PER_100M.rifle_light};
 });
 const ledger={ruleId:'3d-556-bdc-retention-fit-v1',classification:'튜닝(제조사 BDC 역산); 실측 탄도 계수 아님',
  source:{product:'https://www.trijicon.com/products/details/ta31-d-100309',quote:'The ranging reticle is calibrated for 5.56(.223 cal) flattop rifles out to 800 meters.',checked:'2026-10-11',
   productHTTPStatus:200,productBytes:182103,productSHA256:'8f81e44b224c9bcbc7c6027d2a8e0048c22a1b00780c89366d065b65e8c6cc80',
   drawing:old.sources.find(s=>s.id==='acog'),marksMOA:marks,zeroDistanceM:100},
  original:{legacyRetentionTable:CATALOG.DRAG_RETENTION_PER_100M,legacyDeclarationsUnchanged:true,baseline:'a574eed7a9946af9808f53ea45cceb79309b49b6',
   referenceAmmoId:'556_m855',weaponId:'m4a1',muzzleVelocityMps:879,RK4AndGravityUnchanged:true},
  tuning:{method:'golden-section squared MOA error minimum; nested production RK4 zero solve',bracket:[.75,.98],iterations:42,
   classTransfer:'R(class)=R(fit)*legacyRetention(class)/legacyRetention(rifle_light); preserves retention ratios, not logarithmic drag ratios',
   overrides,...fitted,mapping},
  comparison:fitted.rows.map(r=>({...r,v30GameDropMOA:old.report.acog.find(v=>v.distanceM===r.distanceM).gameDrop,
   v30ErrorMOA:old.report.acog.find(v=>v.distanceM===r.distanceM).error,withinOneMOA:Math.abs(r.errorMOA)<=1})),
  acceptance:{ranges,maximumAbsoluteErrorMOA:1,passed:fitted.rows.every(r=>Math.abs(r.errorMOA)<=1),vuduComparisonOnly:true},
  limitations:['One distance-independent retention fit does not reproduce a measured Mach-dependent drag curve',
   'The manufacturer drawing identifies .223/5.56 flattop calibration, not a measured M855 ballistic coefficient or exact load/atmosphere',
   'Vudu SR3 was designed for a different 75gr load; it is not a fit target',
   'Only 3D 5.56 flight changes; distant incident velocity changes downstream results without editing terminal equations']};
 await writeFile(resolve(root,'apps/training/src/generated/flight-tuning.js'),'// Generated by scripts/training-flight-tuning.mjs; tuning from manufacturer BDC, not measured BC.\nexport const RETENTION_BY_CALIBER = Object.freeze('+JSON.stringify(overrides)+');\n');
 await writeFile(resolve(root,'docs/flight-tuning-ledger.json'),JSON.stringify(ledger,null,2)+'\n');return ledger;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify((await generateFlightTuning()).tuning,null,2));
