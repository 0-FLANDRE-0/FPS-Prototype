import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createContext, runInContext } from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
// Run the original initialization, including source switches and manual-derived fields.
// No game loop, DOM, or substitute data is installed in this isolated build context.
export async function extractCatalog() {
  const manifest = JSON.parse(await readFile(resolve(root,'reference/2d/src/manifest.json'), 'utf8'));
  const context = createContext({ console: { log() {}, warn(...args) { throw new Error(args.join(' ')); } } });
  const provenance = [], registries = [];
  let complete = false;
  for (const { path } of manifest.scripts) {
    const source = await readFile(resolve(root, 'reference/2d', path), 'utf8');
    runInContext(source, context, { filename: path, timeout: 5000 });
    provenance.push({ path, sha256: createHash('sha256').update(source).digest('hex') });
    registries.push(...[...source.matchAll(/^const ([A-Z_]+REGISTRY)\s*=/gm)].map(match => match[1]));
    if (path === 'src/data/ammunition-registry.js') { complete = true; break; }
  }
  if (!complete || registries.length !== 12) throw new Error('Original registry initialization boundary changed; review catalog export');
  const tables = ['AMMO_PRESETS', 'AMMO_VELOCITY', 'AMMO_ENERGY_CLASS', 'ARMOR_DAMAGE_PCT', 'AMMO_MEDICAL',
    'AMMO_TERMINAL_PROFILE', 'AMMO_TERMINAL_EFFECT', 'AMMO_DRAG_CLASS', 'DRAG_RETENTION_PER_100M', 'AMMO_LORE',
    'WEAPONS', 'WEAPON_VELOCITY_MUL', 'BODY_ARMOR_PRESETS', 'HELMET_PRESETS', 'PROTECTION_ACCESSORY_PRESETS',
    'PLATE_PRESETS', 'PLATE_MAX_DURABILITY', 'HELMET_MAX_DURABILITY', 'ACCESSORY_MAX_DURABILITY',
    'ARMOR_SOFT_MAX_DURABILITY', 'MATERIAL_PROPS', 'THROWABLE_PRESETS', 'SKILL_PRESETS', 'COMPOSURE_PROFILES',
    'AMMO_REGISTRY_GROUPS', 'WEAPON_REGISTRY_GROUPS', 'HELMET_REGISTRY_GROUPS', 'PLATE_REGISTRY_GROUPS'];
  const data = JSON.parse(runInContext(`JSON.stringify({${[...registries, ...tables].join(',')}})`, context));
  // Match the supplied iron-sight, 14.5-inch M4 model, rather than the original CQBR UI preset.
  const trainingBuild = { weaponId: 'm4a1', platformId: 'ar15_556', presetId: null, customModified: true,
    opticId: 'iron', barrelId: 'ar15_145_m4', muzzleId: 'a2_flash_hider', foregripId: 'none' };
  context.trainingBuild = trainingBuild;
  const trainingProfiles = JSON.parse(runInContext(`JSON.stringify(Object.fromEntries(WEAPON_REGISTRY.m4a1.ammo.allowedAmmoIds.map(id => [id, buildResolvedWeaponProfile('m4a1', id, trainingBuild)])))`, context));
  const akProfiles = JSON.parse(runInContext(`JSON.stringify(Object.fromEntries(WEAPON_REGISTRY.ak74.ammo.allowedAmmoIds.map(id => [id, buildResolvedWeaponProfile('ak74', id)])))`, context));
  const scarProfiles=JSON.parse(runInContext(`JSON.stringify(Object.fromEntries(WEAPON_REGISTRY.scar_h.ammo.allowedAmmoIds.map(id=>[id,buildResolvedWeaponProfile('scar_h',id)])))`,context));
  const kineticsSource = runInContext('computeProjectileKinetics.toString()', context);
  return { data, trainingBuild, trainingProfiles, akProfiles, scarProfiles, provenance, kineticsSource };
}

export async function generateCatalog() {
  if(!process.argv.includes("--allow-reference-import"))throw Error("Reference import is opt-in; normal3Dbuild uses independently owned ported modules.");
  const result = await extractCatalog();
  const path = resolve(root, 'apps/training/src/generated/catalog.js');
  const source = '// Generated by scripts/training-catalog.mjs; edit original registries, then regenerate.\n' +
    `export const SOURCE_HASHES = ${JSON.stringify(result.provenance)};\n` +
    `export const TRAINING_BUILD = ${JSON.stringify(result.trainingBuild)};\n` +
    `export const TRAINING_PROFILES = ${JSON.stringify(result.trainingProfiles)};\n` +
    `export const AK_PROFILES = ${JSON.stringify(result.akProfiles)};\n` +
    `export const SCAR_PROFILES = ${JSON.stringify(result.scarProfiles)};\n` +
    `export const ORIGINAL_TABLES = ${JSON.stringify(result.data)};\n` +
    `export ${result.kineticsSource}\n`;
  await mkdir(resolve(path, '..'), { recursive: true });
  // Avoid touching the generated source when it is already current.
  if (await readFile(path, 'utf8').catch(() => '') !== source) await writeFile(path, source);
  return result;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { data } = await generateCatalog();
  console.log(`Catalog: ${Object.keys(data.AMMO_REGISTRY).length} ammunition / ${Object.keys(data.WEAPON_REGISTRY).length} weapons / all 12 original registries`);
}
