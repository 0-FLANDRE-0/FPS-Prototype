import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { solveZero, flightAtDistance } from './training-zeroing-solver.mjs';
import { FLIGHT_RULE_ID, FLIGHT_LIMITS } from '../apps/training/src/flight.js';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function generateZeroing(flightOptions = {}) {
  const inputs=JSON.parse(await readFile(resolve(root,'docs/zeroing-ledger-inputs.json'),'utf8'));
  const table=Object.fromEntries(inputs.presets.map(p=>[p.opticId||p.weaponId,solveZero(p,flightOptions)]));
  const heights=id=>[25,50,100,200,300,400,500].map(distanceM=>({distanceM,
    heightCm:flightAtDistance(table[id],table[id].thetaRad,distanceM,table[id].referenceAmmoId,flightOptions).heightM*100}));
  const bdc=(id,distances,marks,unit)=>distances.map((distanceM,i)=>{
    const height=flightAtDistance(table[id],table[id].thetaRad,distanceM,table[id].referenceAmmoId,flightOptions).heightM,
      dropRad=-Math.atan2(height,distanceM),factor=unit==='MOA'?10800/Math.PI:1000;
    return{distanceM,mark:marks[i],unit,gameDropCm:-height*100,gameDrop:dropRad*factor,
      error:dropRad*factor-marks[i],errorCm:-height*100-Math.tan(marks[i]/factor)*distanceM*100,
      outsideLiveRange:distanceM>FLIGHT_LIMITS.maxDistanceM};
  });
  const ledger={ruleId:'fixed-sight-zero-v1',...inputs,geometryBasis:'scale 1, stationary ADS; rear sight/ocular at origin, level sight -Z',
    calculation:{flightRuleId:FLIGHT_RULE_ID,method:'production RK4 flightChord + swept arrival interpolation; bisection',toleranceMm:.1,actualSolveToleranceMm:.00001,
      fixedReferenceRound:true,runtimeSolves:0,gravity:FLIGHT_LIMITS.gravity,limits:FLIGHT_LIMITS},
    results:table,report:{m4Iron:heights('m4a1'),xps3:heights('eotech_xps3_0'),
      acog:bdc('trijicon_ta31',[400,500,600,700,800],[7.8,12.6,18.7,26.4,35.8],'MOA'),
      vudu:bdc('vudu_1_6x24',[400,500,600].map(d=>d*.9144),[2,3,4.1],'mrad'),
      causes:['v30 used original .94/100m; v31 uses 3D 5.56 manufacturer BDC inverse-fit tuning, not a measured drag curve',
        'M855 registry velocity 925 m/s becomes 879 m/s through unchanged M4 factor .95 and legacy rounding',
        'SR3 design 75gr/2900fps/BC .395 and 1.5 inch sight height differ from game M855/model mount',
        'ACOG drawing .223/5.56 calibration and real atmospheric/G1/G7 model are not this retention model'],
      ffpZoomIndependent:true,flightChanged:true,flightChange:'3D 5.56-only retention override; RK4/geometry/other calibers unchanged',extrapolation:'700/800m tables only, same equations; live range remains 620m'}};
  await mkdir(resolve(root,'apps/training/src/generated'),{recursive:true});
  await writeFile(resolve(root,'apps/training/src/generated/zeroing.js'), '// Generated by scripts/training-zeroing.mjs; fixed hardware angles, not per-shot solves.\nexport const ZEROING_TABLE = Object.freeze('+JSON.stringify(Object.fromEntries(Object.entries(table).map(([id,p])=>[id,{deviceId:id,weaponId:p.weaponId,referenceAmmoId:p.referenceAmmoId,distanceM:p.distanceM,offsetM:p.offsetM,thetaRad:p.thetaRad,sightHeightMm:p.sightHeightMm,muzzleVelocityMps:p.muzzleVelocityMps}])) )+');\n');
  await writeFile(resolve(root,'docs/zeroing-ledger.json'),JSON.stringify(ledger,null,2)+'\n');
  return ledger;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const l=await generateZeroing();console.log(JSON.stringify(l.results,null,2));
}
